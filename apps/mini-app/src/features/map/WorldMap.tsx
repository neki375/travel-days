import type { CountryDays } from "@travel-days/shared";
import type { FeatureCollection, Geometry } from "geojson";
import { geoEqualEarth, geoPath } from "d3-geo";
import { useMemo, useState, type KeyboardEvent } from "react";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import { countryFlag, countryName } from "../../lib/countries";
import { formatDays } from "../../lib/dates";
import { DAY_BINS, dayBin } from "../../lib/map-scale";
import pointsData from "./country-points.json";
import worldData from "./world-110m.json";

// Map data is static: project it once per app session (generated by scripts/generate-world-map.ts).
type CountryProperties = { name: string };
const world = worldData as unknown as Topology<{
  countries: GeometryCollection<CountryProperties>;
}>;
const points = pointsData as unknown as Record<string, [number, number]>;

const WIDTH = 960;
const collection: FeatureCollection<Geometry, CountryProperties> = feature(
  world,
  world.objects.countries,
);
const projection = geoEqualEarth().fitWidth(WIDTH, collection);
const pathGenerator = geoPath(projection);
const [[, top], [, bottom]] = pathGenerator.bounds(collection);
const VIEW_BOX = `0 ${Math.floor(top)} ${WIDTH} ${Math.ceil(bottom - top)}`;

/** Shapes smaller than this (viewBox units², ~20px² on a phone) are hard to see and tap: add a dot. */
const MIN_SHAPE_AREA = 150;
const DOT_RADIUS = 12;
const DOT_HIT_RADIUS = 36;

const SHAPES = collection.features.map((item, index) => ({
  key: typeof item.id === "string" ? item.id : `unknown-${index}`,
  code: typeof item.id === "string" ? item.id : null,
  name: item.properties.name,
  d: pathGenerator(item) ?? "",
  area: pathGenerator.area(item),
}));
const SHAPE_AREA = new Map(
  SHAPES.flatMap((shape) => (shape.code ? [[shape.code, shape.area]] : [])),
);

interface WorldMapProps {
  countries: readonly CountryDays[];
}

export default function WorldMap({ countries }: WorldMapProps) {
  const [selected, setSelected] = useState<{ code: string; name: string } | null>(null);
  const daysByCode = useMemo(
    () => new Map(countries.map((item) => [item.countryCode, item.days])),
    [countries],
  );

  // Visited countries without a usable shape are shown as dots at their center.
  const dots = useMemo(
    () =>
      countries.flatMap(({ countryCode }) => {
        if ((SHAPE_AREA.get(countryCode) ?? 0) >= MIN_SHAPE_AREA) {
          return [];
        }
        const position = points[countryCode] && projection(points[countryCode]);
        return position ? [{ code: countryCode, x: position[0], y: position[1] }] : [];
      }),
    [countries],
  );

  const select = (code: string, fallbackName: string) =>
    setSelected({ code, name: countryName(code, fallbackName) });
  const onKey = (code: string) => (event: KeyboardEvent) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      select(code, code);
    }
  };

  const selectedDays = selected ? (daysByCode.get(selected.code) ?? 0) : 0;
  const selectedShape = selected && SHAPES.find((shape) => shape.code === selected.code);

  return (
    <figure className="card world-map">
      <svg
        viewBox={VIEW_BOX}
        role="group"
        aria-label="Карта стран, в которых вы были"
        onClick={() => setSelected(null)}
      >
        {SHAPES.map((shape) => {
          const days = shape.code ? (daysByCode.get(shape.code) ?? 0) : 0;
          const visited = days > 0 && shape.code !== null;
          return (
            <path
              key={shape.key}
              d={shape.d}
              className={`map-shape bin-${dayBin(days)}`}
              tabIndex={visited ? 0 : undefined}
              role={visited ? "button" : undefined}
              aria-label={
                visited && shape.code
                  ? `${countryName(shape.code, shape.name)}: ${formatDays(days)}`
                  : undefined
              }
              onClick={(event) => {
                event.stopPropagation();
                if (shape.code) {
                  select(shape.code, shape.name);
                }
              }}
              onKeyDown={shape.code ? onKey(shape.code) : undefined}
            />
          );
        })}

        {/* Drawn again on top so the outline of the selected country is not covered. */}
        {selectedShape && <path d={selectedShape.d} className="map-shape-outline" />}

        {dots.map((dot) => (
          <g
            key={dot.code}
            className={`map-dot bin-${dayBin(daysByCode.get(dot.code) ?? 0)}`}
            tabIndex={0}
            role="button"
            aria-label={`${countryName(dot.code)}: ${formatDays(daysByCode.get(dot.code) ?? 0)}`}
            onClick={(event) => {
              event.stopPropagation();
              select(dot.code, dot.code);
            }}
            onKeyDown={onKey(dot.code)}
          >
            <circle className="map-dot-hit" cx={dot.x} cy={dot.y} r={DOT_HIT_RADIUS} />
            <circle
              className={selected?.code === dot.code ? "map-dot-mark selected" : "map-dot-mark"}
              cx={dot.x}
              cy={dot.y}
              r={DOT_RADIUS}
            />
          </g>
        ))}
      </svg>

      <p className="map-readout" aria-live="polite">
        {selected ? (
          <>
            <span aria-hidden="true">{countryFlag(selected.code)}</span> {selected.name}
            {" — "}
            <strong>{selectedDays > 0 ? formatDays(selectedDays) : "не были в этот период"}</strong>
          </>
        ) : (
          <span className="hint">Нажмите на страну, чтобы увидеть число дней</span>
        )}
      </p>

      <figcaption className="map-legend">
        <span className="hint">Дней в стране:</span>
        {DAY_BINS.map((bin, index) => (
          <span key={bin.label} className="map-legend-item">
            <span className={`map-swatch bin-${index + 1}`} aria-hidden="true" />
            {bin.label}
          </span>
        ))}
        <span className="map-legend-item">
          <span className="map-swatch bin-0" aria-hidden="true" />
          не были
        </span>
      </figcaption>
    </figure>
  );
}
